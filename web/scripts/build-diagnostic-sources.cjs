// Exact generated paths: never authorize arbitrary src/<user-controlled>.js names.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
function buildDiagnosticSources(root,{check=false}={}){
 const files=[];
 function walk(dir){for(const entry of fs.readdirSync(dir,{withFileTypes:true})){const file=path.join(dir,entry.name);if(entry.isDirectory())walk(file);else if(entry.isFile()&&entry.name.endsWith('.js'))files.push(path.relative(root,file).split(path.sep).join('/'));}}
 walk(path.join(root,'src'));const target=path.join(root,'src/runtime/diagnostic-sources.js');
 if(!files.includes('src/runtime/diagnostic-sources.js'))files.push('src/runtime/diagnostic-sources.js');files.sort();
 const content='// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by scripts/build-diagnostic-sources.cjs. Application source paths only.\nexport const diagnosticSources = '+JSON.stringify(files,null,1)+';\n';
 if(check)assert.equal(fs.readFileSync(target,'utf8'),content,'Diagnostic source paths are stale');else fs.writeFileSync(target,content);
 return files;
}
module.exports={buildDiagnosticSources};
if(require.main===module)buildDiagnosticSources(path.resolve(__dirname,'..'),{check:process.argv.includes('--check')});
