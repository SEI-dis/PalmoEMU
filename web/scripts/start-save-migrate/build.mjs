// Assemble reviewed source text. Never evaluate supplied code during a build.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

export const sourceDirectory=fileURLToPath(new URL('./',import.meta.url));
export const engineFile=fileURLToPath(new URL('../../vendor/start-save-migrate/engine.js',import.meta.url));
const manifestFile=fileURLToPath(new URL('../../vendor/start-save-migrate/manifest.js',import.meta.url));
const hash=value=>createHash('sha256').update(value).digest('hex');
export function assembleEngine(template,patches,manifest){
 assert.equal(patches.schema,1,'Unsupported START patch record');
 assert.equal(hash(template),patches.templateSha256,'START extraction template changed; review before rebasing');
 assert.equal(hash(manifest),patches.manifestSha256,'START supplied definitions changed; review local patches before rebasing');
 assert(Array.isArray(patches.changes)&&patches.changes.length>0,'Missing START local changes');
 let result=template.toString('utf8');const ids=new Set();
 for(const patch of patches.changes){
  assert(typeof patch.id==='string'&&/^[a-z][a-z0-9-]+$/.test(patch.id)&&!ids.has(patch.id),'Invalid or duplicate START patch');ids.add(patch.id);
  assert(typeof patch.reason==='string'&&patch.reason.trim()&&typeof patch.code==='string'&&patch.code.trim(),'Document the START patch and its implementation');
  const marker=`/* PALMO_PATCH:${patch.id} */`;
  assert.equal(result.split(marker).length,2,'Missing or ambiguous START patch anchor: '+patch.id);
  assert(!patch.code.includes('PALMO_PATCH:'),'Patch cannot introduce another patch anchor');
  result=result.replace(marker,()=>patch.code);
 }
 assert(!result.includes('PALMO_PATCH:'),'Unapplied START patch');
 return '// Generated by scripts/start-save-migrate/build.mjs; edit the reviewed template/patches, not this file.\n'+result;
}
export function buildEngine({check=false,directory=sourceDirectory,output=engineFile,manifest=manifestFile}={}){
 const template=fs.readFileSync(path.join(directory,'base/engine.template.txt'));
 const patches=JSON.parse(fs.readFileSync(path.join(directory,'patches.json'),'utf8'));
 const result=assembleEngine(template,patches,fs.readFileSync(manifest));
 // Retain the distributed engine's CRLF bytes on every build host.
 const bytes=result.replaceAll('\n','\r\n');
 if(check)assert.equal(fs.readFileSync(output,'utf8'),bytes,'START generated engine is stale');
 else if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==bytes)fs.writeFileSync(output,bytes);
 return result;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 try{assert(process.argv.slice(2).every(arg=>arg==='--check'),'Usage: build.mjs [--check]');buildEngine({check:process.argv.includes('--check')});console.log('PASS: START extraction and separate PalmoEMU patches reproduce the runtime engine.');}
 catch(error){console.error(error.message);process.exitCode=1;}
}
